import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { contentSchemas } from './lib/schemas';
const posts = defineCollection({ loader: glob({ pattern: '**/*.md', base: './src/content/posts' }), schema: contentSchemas.posts });
const memos = defineCollection({ loader: glob({ pattern: '**/*.md', base: './src/content/memos' }), schema: contentSchemas.memos });
const projects = defineCollection({ loader: glob({ pattern: '**/*.json', base: './src/content/projects' }), schema: contentSchemas.projects });
const media = defineCollection({ loader: glob({ pattern: '**/*.json', base: './src/content/media' }), schema: contentSchemas.media });
const friends = defineCollection({ loader: glob({ pattern: '**/*.json', base: './src/content/friends' }), schema: contentSchemas.friends });
const pages = defineCollection({ loader: glob({ pattern: '**/*.md', base: './src/content/pages' }), schema: contentSchemas.pages });
export const collections = { posts, memos, projects, media, friends, pages };
